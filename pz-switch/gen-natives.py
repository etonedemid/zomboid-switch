#!/usr/bin/env python3
"""Generates the Java side's native-library glue:
  natives-out/jni_stubs.S  - every native method in pz.jar not provided by a real library: logs once, returns 0
  natives-out/dltab.c      - name -> address table of every symbol the static "shared libraries" export (for lx_dl)
usage: gen-natives.py <pz.jar> <outdir> <real lib objects...>"""
import os, re, struct, subprocess, sys, zipfile

jar, out, real_objs = sys.argv[1], sys.argv[2], [a for a in sys.argv[3:] if not a.startswith('--')]
# JDK modules (.jmod) whose initIDs natives get stubs too: no libawt here, and ImageIO only needs them to exist
jmods = [a[7:] for a in sys.argv[3:] if a.startswith('--jmod=')]
libc = [a[7:] for a in sys.argv[3:] if a.startswith('--libc=')]  # archives whose every global is exported (box64's wrapped libc dlsyms them)

def natives(data):
    """(class name, [(method name, descriptor)]) for methods with ACC_NATIVE in a class file"""
    pos = 10
    n = struct.unpack('>H', data[8:10])[0]
    cp = [None] * n
    i = 1
    while i < n:
        tag = data[pos]
        if tag == 1:
            ln = struct.unpack('>H', data[pos + 1:pos + 3])[0]
            cp[i] = data[pos + 3:pos + 3 + ln].decode('utf-8', 'replace'); pos += 3 + ln
        elif tag in (7, 8, 16, 19, 20): cp[i] = struct.unpack('>H', data[pos + 1:pos + 3])[0]; pos += 3
        elif tag == 15: pos += 4
        elif tag in (3, 4, 9, 10, 11, 12, 17, 18): pos += 5
        elif tag in (5, 6): pos += 9; i += 1
        else: raise ValueError('bad cp tag %d' % tag)
        i += 1
    this = cp[cp[struct.unpack('>H', data[pos + 2:pos + 4])[0]]]
    pos += 6
    nif = struct.unpack('>H', data[pos:pos + 2])[0]; pos += 2 + 2 * nif
    for _ in range(2):  # fields, then methods
        cnt = struct.unpack('>H', data[pos:pos + 2])[0]; pos += 2
        res = []
        for _ in range(cnt):
            flags, ni, di, na = struct.unpack('>HHHH', data[pos:pos + 8]); pos += 8
            for _ in range(na):
                ln = struct.unpack('>I', data[pos + 2:pos + 6])[0]; pos += 6 + ln
            if flags & 0x100: res.append((cp[ni], cp[di]))
    return this, res

def mangle(s):
    o = []
    for ch in s:
        if ch == '/': o.append('_')
        elif ch == '_': o.append('_1')
        elif ch == ';': o.append('_2')
        elif ch == '[': o.append('_3')
        elif ch.isalnum() and ord(ch) < 128: o.append(ch)
        else: o.append('_0%04x' % ord(ch))
    return ''.join(o)

# symbols already provided by real libraries
real = set()
tls = set()  # thread-locals can't be referenced as plain addresses in the dlsym table
for obj in real_objs:
    for line in subprocess.run(['aarch64-linux-gnu-readelf', '-sW', obj], capture_output=True, text=True).stdout.splitlines():
        p = line.split()
        if len(p) >= 8 and p[3] == 'TLS': tls.add(p[7])
for obj in real_objs:
    for line in subprocess.run(['aarch64-linux-gnu-nm', '--defined-only', '-g', obj], capture_output=True, text=True).stdout.splitlines():
        p = line.split()
        if len(p) == 3: real.add(p[2])

stubs = {}  # symbol -> "Class.method"
sigs = {}   # short JNI symbol -> method descriptor (for the x86 bridge)
def classes():
    zf = zipfile.ZipFile(jar)
    for n in zf.namelist():
        if n.endswith('.class') and not n.startswith(('META-INF/', 'org/lwjgl/')): yield zf.read(n), None
    for m in jmods:
        zf = zipfile.ZipFile(m)  # a jmod is a zip behind a 4-byte header; zipfile finds it from the end
        for n in zf.namelist():
            if n.startswith('classes/') and n.endswith('.class'): yield zf.read(n), 'initIDs'
for data, only in classes():
    if data[:4] != b'\xca\xfe\xba\xbe': continue
    try: cls, ms = natives(data)
    except Exception: continue
    for name, desc in ms:
        if only and name != only: continue
        base = 'Java_' + mangle(cls) + '_' + mangle(name)
        sigs.setdefault(base, desc)
        args = desc[1:desc.index(')')]
        for sym in (base, base + '__' + mangle(args)):
            if sym not in real: stubs[sym] = cls.replace('/', '.') + '.' + name

os.makedirs(out, exist_ok=True)
names = sorted(stubs)
with open(os.path.join(out, 'jni_stubs.S'), 'w') as f:
    f.write('// generated by gen-natives.py: JNI stubs that log their name once and return 0 (x0 and d0)\n.text\n')
    for i, s in enumerate(names):
        f.write('.global %s\n.type %s, %%function\n%s:\n  mov w9, #%d\n  b lx_jni_stub_common\n' % (s, s, s, i))
    f.write('''
.global lx_jni_stub_common
lx_jni_stub_common:
  stp x29, x30, [sp, #-16]!
  mov w0, w9
  bl lx_jni_stub_hit
  mov x0, #0
  movi d0, #0
  ldp x29, x30, [sp], #16
  ret
.data
.global lx_jni_stub_names
lx_jni_stub_names:
''')
    for s in names: f.write('  .quad .Ln_%s\n' % s)
    for s in names: f.write('.Ln_%s: .asciz "%s"\n' % (s, stubs[s]))
    f.write('.global lx_jni_stub_count\nlx_jni_stub_count: .quad %d\n' % len(names))
print('%d stubbed JNI symbols, %d real exports' % (len(names), len(real)))

# dlsym table: every global defined in the real objects + the stubs
libc_syms = set()
for a in libc:
    for line in subprocess.run(['aarch64-linux-gnu-nm', '--defined-only', '-g', a], capture_output=True, text=True).stdout.splitlines():
        p = line.split()
        if len(p) == 3 and p[1] in 'TWDBRV' and '.' not in p[2] and not re.match(r'_*dl[a-z_]', p[2]): libc_syms.add(p[2])  # musl's dl* is replaced by lx_dl
exported = sorted((set(s for s in real if not s.startswith('_')) | set(names) | libc_syms) - tls)
with open(os.path.join(out, 'dltab.c'), 'w') as f:
    f.write('/* generated by gen-natives.py */\n#include <stddef.h>\n')
    for s in exported: f.write('extern char %s[];\n' % s)
    f.write('const struct lx_sym { const char *name; void *addr; } lx_dltab[] = {\n')
    for s in exported: f.write('  { "%s", %s },\n' % (s, s))
    f.write('};\nconst size_t lx_dltab_len = %d;\n' % len(exported))
    f.write('const struct lx_jni_sig { const char *name, *desc; } lx_jni_sigs[] = {\n')
    for k in sorted(sigs): f.write('  { "%s", "%s" },\n' % (k, sigs[k]))
    f.write('};\nconst size_t lx_jni_sigs_len = %d;\n' % len(sigs))
print('%d dlsym entries' % len(exported))
